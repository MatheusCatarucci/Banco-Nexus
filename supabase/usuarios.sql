-- Schema da tabela usuarios + indice unico do CPF.
-- Rode no SQL Editor do Supabase. Tudo aqui e idempotente: pode rodar de novo
-- sem quebrar nada.

create table if not exists public.usuarios (
  id bigint generated by default as identity not null,
  "NOME" character varying not null,
  "CPF" bigint null,
  "SENHA" character varying null,
  "SALDO" double precision null,
  constraint usuarios_pkey primary key (id)
);

-- 1) CPF e o login, entao precisa ser unico.
create unique index if not exists usuarios_cpf_uniq on public.usuarios (CPF);

-- 2) A controller sempre grava os dois campos.
alter table public.usuarios
  alter column SENHA set not null,
  alter column SALDO set default 0;

